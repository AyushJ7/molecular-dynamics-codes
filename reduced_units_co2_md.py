def calculate_msd(N, coord):
  cx = coord[:,0]
  cy = coord[:,1]
  cz = coord[:,2]

  msd = np.zeros(N-1)
  for i in range(1,N): # Considering 1 step movements to N-1 step movements
    for j in range(N-i):
      msd[i-1]+= ((cx[j+i]-cx[j])**2 + (cy[j+i]-cy[j])**2 + (cz[j+i]-cz[j])**2)

    msd[i-1]/=(N-i)

  return msd

